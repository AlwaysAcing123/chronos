function ManualTrading({ guide }: { readonly guide: Guide }) {
  return (
    <Panel title="1. Manual paper trading" meta="Trading">
      <ol className={styles.list}>
        <Step>
          Press <strong>Start replay</strong> in the source bar, then open <a href={guide.seed.routes.trading}>Trading</a>.
          Quotes for AAPL and SPY arrive at 1x.
        </Step>
        <Step>Create a paper account with a new ID, such as demo-manual-1. You own it; no model can trade it.</Step>
        <Step>
          In the order ticket, buy 1 AAPL at market: <strong>Review order</strong>, then <strong>Submit paper order</strong>
          . It fills at the best displayed ask.
        </Step>
        <Step>
          Read the order, its fill, and the portfolio. Cash falls by the fill’s notional and the 0.01 fee; the position is
          valued at the best bid, so its profit starts below zero by the spread and the fee.
        </Step>
        <Step>
          Place a limit buy well below the bid, such as 90, good til cancelled. It rests in <strong>Working orders</strong>{' '}
          and reserves cash: the limit times the quantity, plus the fee until its first fill. Available cash falls; cash
          does not.
        </Step>
        <Step>Cancel it. The reservation is released, and available cash returns.</Step>
      </ol>
      <p className={styles.note}>
        Displayed liquidity: a fill takes at most the size the quote displays, and one account cannot take the same
        displayed shares twice. A paper order never reaches an exchange, so it removes no real shares from any book, and
        each account is its own simulated world.
      </p>
    </Panel>
  );
}

function ModelDeployment({ guide }: { readonly guide: Guide }) {
  const { routes, chronology } = guide.seed;
  const logistic = chronology.model_cutoffs.find((cutoff) => cutoff.family === 'logistic');
  return (
    <Panel title="2. Evaluate, then paper-deploy a model" meta="Models · Comparisons · Research">
      <ol className={styles.list}>
        <Step>
          Open the registered <a href={routes.models.logistic}>logistic model</a>, fitted on the training part of
          history session h3 alone and verified whenever it is read.
          {logistic !== undefined && (
            <>
              {' '}
              Its information cutoff, <MarketTime value={logistic.at} /> UTC, precedes the playback session, so a
              deployment may decide on it.
            </>
          )}
        </Step>
        <Step>
          Review its historical evaluation: the <a href={routes.comparison}>comparison</a> runs it beside the{' '}
          <a href={routes.models.majority}>majority baseline</a> on h3’s test window, with the frozen policy, fee, and
          latency. You can also start an evaluation of your own in <a href={routes.research}>Research</a>; it runs as a
          real job.
        </Step>
        <Step>
          On the model’s page, choose <strong>Deploy this version to paper</strong> with a new deployment ID and a new
          account ID. The deployment is created stopped, with an account only it may trade.
        </Step>
        <Step>
          In <a href={routes.research}>Research</a>, under <strong>Paper deployments</strong>, press{' '}
          <strong>Start</strong> and confirm. Only then does its worker load the model.
        </Step>
        <Step>
          Watch its decisions: each saved prediction, the policy’s reason, and any order, which the order list marks as
          Model. <strong>Open in trading</strong> shows its account’s orders and fills.
        </Step>
        <Step>
          Press <strong>Stop</strong>. The model stops deciding. Stop never sells: any shares it bought stay in its
          account.
        </Step>
      </ol>
      <p className={styles.note}>
        An evaluation and a deployment assume different execution. The evaluation fills the dataset’s first quote at or
        after each scheduled order; the deployment trades the quote current when its order is accepted, and rows that
        arrive while it is busy are skipped. Their decisions, timing, and profit are not expected to match.
      </p>
    </Panel>
  );
}

function StrategyResult({ guide, selectedAccountId }: { readonly guide: Guide; readonly selectedAccountId: string | null }) {
  const { routes, audits } = guide.seed;
  const study = routes.studies.AAPL;
  return (
    <Panel title="3. Explain a strategy result" meta="Research · Walk-forward">
      <ol className={styles.list}>
        <Step>
          Open the {study === undefined ? 'AAPL walk-forward study' : <a href={study}>AAPL walk-forward study</a>}: fresh
          models trained on h1, then on h1 and h2, each measured on the next session under base and stress costs.
        </Step>
        <Step>
          Open its <a href={routes.diagnostics}>strategy diagnostics</a> and{' '}
          {typeof routes.diagnostics_run === 'string' ? (
            <a href={routes.diagnostics_run}>the first fold’s logistic base run</a>
          ) : (
            <>the first fold’s logistic base run, which is unavailable ({routes.diagnostics_run.unavailable})</>
          )}
          .
        </Step>
        <Step>
          Read its exact profit attribution: the spread paid, the fees, and the final mark at the best bid, each the
          engine’s exact decimal.
        </Step>
        <Step>
          Tell the checks apart: what was reconciled when the diagnostics were generated, what this read verified again,
          and the independent auditor, which passed {audits.strategy_diagnostics.checks_total} checks when the workspace
          was seeded.
        </Step>
        <Step>
          Return to <a href={TRADING_HREF}>Trading</a>.{' '}
          {selectedAccountId === null
            ? 'No paper account was selected, and none is.'
            : `The account you had open, ${selectedAccountId}, is still selected.`}
        </Step>
      </ol>
    </Panel>
  );
}

function Provenance({ guide }: { readonly guide: Guide }) {
  const { seed } = guide;
  return (
    <Panel title="Where this data came from" meta={`${seed.scenario.name} version ${seed.scenario.version}`}>
      <Facts
        facts={[
          { label: 'Evidence', value: <Badge tone="caution">Synthetic</Badge> },
          { label: 'Scenario', value: `${seed.scenario.name} version ${seed.scenario.version}` },
          { label: 'Seed', value: <Code>{seed.seed_id}</Code> },
        ]}
      />
      <section className={styles.section}>
        <h3 className={styles.sectionTitle}>Sessions</h3>
        <ul className={styles.list}>
          {seed.scenario.sessions.map((session) => (
            <li key={session.name}>
              {session.name} ({session.role}): <MarketTime value={session.receive_first} /> to{' '}
              <MarketTime value={session.receive_last} /> UTC, {session.events} events
            </li>
          ))}
        </ul>
      </section>
      <section className={styles.section}>
        <h3 className={styles.sectionTitle}>Audits when seeded</h3>
        <ul className={styles.list}>
          {Object.entries(seed.audits.walk_forward).map(([instrument, audit]) => (
            <li key={instrument}>
              {instrument} walk-forward study: {audit.verdict}, {audit.checks_total} checks
            </li>
          ))}
          <li>
            Strategy diagnostics: {seed.audits.strategy_diagnostics.verdict},{' '}
            {seed.audits.strategy_diagnostics.checks_total} checks
          </li>
        </ul>
      </section>
      <section className={styles.section}>
        <h3 className={styles.sectionTitle}>Chronology, checked when seeded</h3>
        <ul className={styles.list}>
          {seed.chronology.checks.map((check) => (
            <li key={check}>{check}</li>
          ))}
        </ul>
      </section>
    </Panel>
  );
}

export function DemoGuide({ selectedAccountId }: { readonly selectedAccountId: string | null }) {
  const guide = useDemoGuide();
  return (
    <div className={styles.research}>
      <div className={workspaceStyles.heading}>
        <div>
          <p className={workspaceStyles.eyebrow}>Demo guide</p>
          <h1 className={workspaceStyles.title}>Three guided flows</h1>
        </div>
        <p className={workspaceStyles.workspaceNote}>Invented prices; nothing here starts on its own</p>
      </div>
      {guide.status === 'pending' ? (
        <p role="status">Loading the guide…</p>
      ) : guide.status === 'error' ? (
        <ResearchFailure
          error={guide.error}
          title="The guide's data could not be read"
          onRetry={() => void guide.refetch()}
          retrying={guide.isFetching}
        />
      ) : (
        <>
          <Alert tone="caution" title="Every price here is invented">
            <p>{guide.data.seed.notice}</p>
          </Alert>
          <SessionNotice guide={guide.data} />
          <Concepts />
          <ManualTrading guide={guide.data} />
          <ModelDeployment guide={guide.data} />
          <StrategyResult guide={guide.data} selectedAccountId={selectedAccountId} />
          <Provenance guide={guide.data} />
        </>
      )}
    </div>
  );
}
